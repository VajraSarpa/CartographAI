"use client";

import { useState } from "react";
import { RichText } from "./RichText";

type Target = { kind: "file"; path: string } | { kind: "module"; module: string };
type Result = { content: string; cached: boolean; inventedPaths: string[]; model: string };

export function ExplainPanel({ analysisId, target }: { analysisId: string; target: Target }) {
  const key = target.kind === "file" ? `f:${target.path}` : `m:${target.module}`;
  return <ExplainInner key={key} analysisId={analysisId} target={target} />;
}

function ExplainInner({ analysisId, target }: { analysisId: string; target: Target }) {
  const [state, setState] = useState<{ loading: boolean; result: Result | null; error: string | null }>({ loading: false, result: null, error: null });
  const run = async () => {
    setState({ loading: true, result: null, error: null });
    try {
      const res = await fetch(`/api/analyses/${analysisId}/explain`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(target),
      });
      const body = await res.json();
      if (!res.ok) throw new Error(body.error ?? `Request failed (${res.status})`);
      setState({ loading: false, result: body as Result, error: null });
    } catch (e) {
      setState({ loading: false, result: null, error: (e as Error).message });
    }
  };
  const r = state.result;
  return (
    <div className="space-y-3">
      <div className="flex items-center gap-2">
        <button type="button" onClick={run} disabled={state.loading} className="rounded-md bg-accent px-3 py-1.5 text-xs font-medium text-white disabled:opacity-60">
          {state.loading ? "Explaining…" : r ? "Explain again" : "Explain"}
        </button>
        {r && <span className="text-[11px] text-muted">{r.cached ? "From cache (no model call)" : `Generated by ${r.model}`}</span>}
      </div>
      <p className="text-[11px] text-muted">Built from the parsed import graph and the file at the analyzed commit. It describes; it does not judge.</p>
      {state.error && (
        <p role="alert" className="text-xs text-warn">
          {state.error}
        </p>
      )}
      {r && (
        <>
          {r.inventedPaths.length > 0 && (
            <p className="rounded border border-warn/40 bg-warn/10 p-2 text-xs text-warn">
              The explanation named {r.inventedPaths.length} path{r.inventedPaths.length === 1 ? "" : "s"} it was not shown. They are struck through below.
            </p>
          )}
          <RichText text={r.content} invented={new Set(r.inventedPaths)} />
        </>
      )}
    </div>
  );
}

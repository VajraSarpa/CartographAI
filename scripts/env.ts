const AGENT_KEYS = ["ANTHROPIC_API_KEY", "ANTHROPIC_MODEL", "LANGSMITH_API_KEY", "LANGSMITH_PROJECT", "LANGSMITH_ENDPOINT"];

function readEnv(file: string): Map<string, string> {
  const m = new Map<string, string>();
  if (!existsSync(file)) return m;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (match) m.set(match[1], match[2].replace(/^"(.*)"$/, "$1"));
  }
  return m;
}

function writeEnv(file: string, values: Map<string, string>, header: string) {
  const lines = [`# ${header}`, "# Generated by `pnpm env:setup`. Never commit this file.", ""];
  for (const [k, v] of values) if (v !== "") lines.push(`${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`);
  writeFileSync(file, lines.join("\n") + "\n", { mode: 0o600 });
  chmodSync(file, 0o600);
}

function ask(question: string, hidden: boolean): Promise<string> {
  return new Promise((resolve) => {
    const rl = readline.createInterface({ input: stdin, output: stdout, terminal: true });
    if (hidden) {
      // mute echo
      (rl as unknown as { _writeToOutput: (s: string) => void })._writeToOutput = (s: string) => {
        if (s.includes(question)) stdout.write(s);
        else if (s === "\r\n" || s === "\n") stdout.write(s);
        else stdout.write("*");
      };
    }
    rl.question(question, (a) => {
      rl.close();
      if (hidden) stdout.write("\n");
      resolve(a.trim());
    });
  });
}

async function setup(only: string[] | null) {
  const env = readEnv(".env.local");
  for (const g of GROUPS) {
    if (only && !only.includes(g.id)) continue;
    console.log(`\n== ${g.name} ==\n   where: ${g.where}`);
    for (const f of g.fields) {
      const cur = env.get(f.key);
      const shown = cur ? (f.secret ? "(set, Enter keeps)" : `[${cur}]`) : f.default ? `[${f.default}]` : f.optional ? "(optional, Enter skips)" : "";
      let v = await ask(`   ${f.label} ${shown}: `, !!f.secret);
      if (!v) v = cur ?? f.default ?? "";
      if (v && f.validate && !f.validate.test(v)) {
        console.log(`   ! that doesn't look right for ${f.key}; kept it anyway, run \`pnpm env:check\` after.`);
      }
      if (v) env.set(f.key, v);
    }
  }
  writeEnv(".env.local", env, "Cartograph app environment");
  console.log("\nWrote .env.local (mode 600).");
  if (existsSync("cartograph-agent")) {
    const agent = readEnv("cartograph-agent/.env");
    for (const k of AGENT_KEYS) if (env.get(k)) agent.set(k, env.get(k)!);
    writeEnv("cartograph-agent/.env", agent, "Cartograph agent environment");
    console.log("Wrote cartograph-agent/.env (mode 600).");
  }
}

async function doctor(): Promise<boolean> {
  const env = readEnv(".env.local");
  const { serverSchema } = await import("../src/lib/env");
  const merged = Object.fromEntries([...env.entries()]);
  const parsed = serverSchema.safeParse(merged);
  console.log(`.env.local: ${existsSync(".env.local") ? "found" : "MISSING"}`);
  for (const g of GROUPS) {
    const states = g.fields.map((f) => `${f.key}=${env.get(f.key) ? "set" : f.optional || f.default ? "default/optional" : "MISSING"}`);
    console.log(`  ${g.name}: ${states.join(", ")}`);
  }
  for (const k of ["AGENT_URL", "AGENT_SIGNING_KEY", "AGENT_SIGNING_KID", "APP_URL"]) console.log(`  ${k}: ${env.get(k) ? "set" : "not set"}`);
  let languagesOk = true;
  try {
    const { loadLanguages } = await import("../src/parser/languages");
    const { languagesFromEnv } = await import("../src/lib/env");
    const langs = await loadLanguages(languagesFromEnv(merged));
    console.log(`  CARTOGRAPH_LANGUAGES: ${langs.map((l) => `${l.id} (${l.name})`).join(", ")}`);
  } catch (e) {
    languagesOk = false;
    console.log(`  CARTOGRAPH_LANGUAGES: ${(e as Error).message}`);
  }
  if (!parsed.success) {
    console.log("\nProblems:");
    for (const i of parsed.error.issues) console.log(`  - ${i.path.join(".")}: ${i.message}`);
  } else console.log("\nAll required values present.");
  const ignored = existsSync(".gitignore") && /^\.env\*/m.test(readFileSync(".gitignore", "utf8"));
  console.log(`.env files git-ignored: ${ignored ? "yes" : "NO - fix .gitignore"}`);
  return parsed.success && ignored && languagesOk;
}

async function probe(name: string, fn: () => Promise<Response>, ok = (r: Response) => r.ok): Promise<boolean> {
  try {
    const r = await fn();
    const good = ok(r);
    console.log(`  ${good ? "ok  " : "FAIL"} ${name}${good ? "" : ` (HTTP ${r.status})`}`);
    return good;
  } catch (e) {
    console.log(`  FAIL ${name} (${(e as Error).message})`);
    return false;
  }
}

async function check(): Promise<boolean> {
  const env = readEnv(".env.local");
  const t = AbortSignal.timeout(15_000);
  const results: boolean[] = [];
  if (env.get("CLERK_SECRET_KEY"))
    results.push(await probe("Clerk secret key", () => fetch("https://api.clerk.com/v1/organizations?limit=1", { headers: { Authorization: `Bearer ${env.get("CLERK_SECRET_KEY")}` }, signal: t })));
  const sb = env.get("NEXT_PUBLIC_SUPABASE_URL")?.replace(/\/$/, "");
  if (sb && env.get("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY"))
    results.push(await probe("Supabase publishable key", () => fetch(`${sb}/auth/v1/settings`, { headers: { apikey: env.get("NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY")! }, signal: t })));
  if (sb && env.get("SUPABASE_SECRET_KEY"))
    results.push(
      await probe("Supabase secret key + schema", () =>
        fetch(`${sb}/rest/v1/organizations?select=id&limit=1`, { headers: { apikey: env.get("SUPABASE_SECRET_KEY")!, Authorization: `Bearer ${env.get("SUPABASE_SECRET_KEY")}` }, signal: t }),
      ),
    );
  if (env.get("ANTHROPIC_API_KEY"))
    results.push(await probe("Anthropic API key", () => fetch("https://api.anthropic.com/v1/models?limit=1", { headers: { "x-api-key": env.get("ANTHROPIC_API_KEY")!, "anthropic-version": "2023-06-01" }, signal: t })));
  if (env.get("LANGSMITH_API_KEY"))
    results.push(
      await probe("LangSmith API key", () =>
        fetch(`${(env.get("LANGSMITH_ENDPOINT") ?? "https://api.smith.langchain.com").replace(/\/$/, "")}/api/v1/sessions?limit=1`, { headers: { "x-api-key": env.get("LANGSMITH_API_KEY")! }, signal: t }),
      ),
    );
  if (env.get("GITHUB_TOKEN"))
    results.push(await probe("GitHub token", () => fetch("https://api.github.com/rate_limit", { headers: { Authorization: `Bearer ${env.get("GITHUB_TOKEN")}`, "User-Agent": "cartograph" }, signal: t })));
  if (!results.length) console.log("  nothing to check yet: run `pnpm env:setup`");
  return results.every(Boolean);
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const onlyIdx = rest.indexOf("--only");
  const only = onlyIdx >= 0 ? rest[onlyIdx + 1]?.split(",") ?? null : null;
  if (cmd === "setup") return setup(only);
  if (cmd === "doctor") process.exit((await doctor()) ? 0 : 1);
  if (cmd === "check") process.exit((await check()) ? 0 : 1);
  console.log("usage: pnpm env:setup [--only clerk,supabase,anthropic,langsmith,github] | env:doctor | env:check");
}
main();
